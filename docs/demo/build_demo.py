#!/usr/bin/env python3
"""Builds the demo page the README screenshots are taken from.

Everything here is FICTIONAL — a made-up athlete, a made-up race, made-up
numbers. The real dashboard contains health data and a real race date, which
have no business in a public repository. This file exists so the screenshots
can be regenerated by anyone without exposing anyone.

The stylesheet is extracted verbatim from `harness/rapport.py`, so the demo
looks exactly like the real thing. If the real dashboard is restyled, re-run:

    python3 docs/demo/build_demo.py && open docs/demo/demo.html

then re-screenshot the six sections into docs/images/.
"""
from pathlib import Path

BASE = Path(__file__).resolve().parent
