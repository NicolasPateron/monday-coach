# --------------------------------------------------------------------------
# The invented athlete. Deliberately unlike anyone real.
# --------------------------------------------------------------------------
RACE, RACE_DATE, TARGET = "Valencia Marathon", "Sunday, December 6, 2026", "3:29"
WEEKS = 24

W, H = 880, 260
PAD = {"l": 58, "r": 20, "t": 26, "b": 30}


def scale(vmin, vmax):
    span = (vmax - vmin) or 1
    return lambda v: H - PAD["b"] - (v - vmin) / span * (H - PAD["t"] - PAD["b"])


def y_axis(vmin, vmax, sy, fmt):
    out = []
    for i in range(4):
        v = vmin + (vmax - vmin) * i / 3
        y = sy(v)
        out.append(f'<line class="grid" x1="{PAD["l"]}" y1="{y:.1f}" x2="{W-PAD["r"]}" y2="{y:.1f}"/>')
        out.append(f'<text class="tick" x="{PAD["l"]-8}" y="{y+3:.1f}" text-anchor="end">{fmt(v)}</text>')
    return "".join(out)


def path_of(points):
    return "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in points)


def week_chart(title, subtitle, series, vmin, vmax, fmt=lambda v: f"{v:g}", colour="c-run"):
    sx = lambda s: PAD["l"] + (s - 1) / (WEEKS - 1) * (W - PAD["l"] - PAD["r"])
    sy = scale(vmin, vmax)
    parts = [y_axis(vmin, vmax, sy, fmt)]

    for s, label in [(4, "test"), (11, "retest"), (18, "tune-up"), (24, "RACE")]:
        x = sx(s)
        parts.append(f'<line class="jalon" x1="{x:.1f}" y1="{PAD["t"]}" x2="{x:.1f}" y2="{H-PAD["b"]}"/>')
        parts.append(f'<text class="jalon-txt" x="{x:.1f}" y="{PAD["t"]-6}" text-anchor="middle">{label}</text>')

    bar_w = (W - PAD["l"] - PAD["r"]) / WEEKS * 0.62
    for label, pts, style in series:
        pts = [(s, v) for s, v in pts if v is not None]
        if not pts:
            continue
        if style.startswith("bar"):
            cls = "bar-ref" if style == "bar_ref" else f"bar-reel {colour}"
            for s, v in pts:
                x, y = sx(s) - bar_w / 2, sy(v)
                parts.append(f'<rect class="{cls}" x="{x:.1f}" y="{y:.1f}" width="{bar_w:.1f}" '
                             f'height="{max(0, (H - PAD["b"]) - y):.1f}" rx="2"/>')
        else:
            cls = "line-ref" if style == "reference" else f"line-reel {colour}"
            parts.append(f'<path class="{cls}" d="{path_of([(sx(s), sy(v)) for s, v in pts])}"/>')
            if style == "real":
                for s, v in pts:
                    parts.append(f'<circle class="pt {colour}" cx="{sx(s):.1f}" cy="{sy(v):.1f}" r="4"/>')

    legend = "".join(
        f'<span class="lg"><i class="sw {"ref" if st in ("reference", "bar_ref") else colour}"></i>{lb}</span>'
        for lb, _, st in series)
    return f"""<figure class="card">
  <figcaption><h3>{title}</h3><p>{subtitle}</p></figcaption>
  <div class="legend">{legend}</div>
  <svg viewBox="0 0 {W} {H}" role="img" aria-label="{title}">{''.join(parts)}</svg>
</figure>"""


def day_chart(title, subtitle, values, vmin, vmax, fmt=lambda v: f"{v:g}", band=None, colour="c-blue"):
    n = len(values)
    sx = lambda i: PAD["l"] + i / max(1, n - 1) * (W - PAD["l"] - PAD["r"])
    sy = scale(vmin, vmax)
    parts = []
    if band:
        y1, y2 = sy(band[1]), sy(band[0])
        parts.append(f'<rect class="bande" x="{PAD["l"]}" y="{y1:.1f}" '
                     f'width="{W-PAD["l"]-PAD["r"]}" height="{y2-y1:.1f}"/>')
    parts.append(y_axis(vmin, vmax, sy, fmt))
    pts = [(sx(i), sy(v)) for i, v in enumerate(values)]
    parts.append(f'<path class="line-reel {colour}" d="{path_of(pts)}"/>')
    for x, y in pts:
        parts.append(f'<circle class="pt {colour}" cx="{x:.1f}" cy="{y:.1f}" r="3.5"/>')
    return f"""<figure class="card">
  <figcaption><h3>{title}</h3><p>{subtitle}</p></figcaption>
  <svg viewBox="0 0 {W} {H}" role="img" aria-label="{title}">{''.join(parts)}</svg>
</figure>"""


def dot_chart(title, subtitle, values, vmin, vmax, fmt, band):
    """Scatter over many nights — the sleep chart."""
    n = len(values)
    sx = lambda i: PAD["l"] + i / max(1, n - 1) * (W - PAD["l"] - PAD["r"])
    sy = scale(vmin, vmax)
    parts = []
    if band:
        y1, y2 = sy(band[1]), sy(band[0])
        parts.append(f'<rect class="bande" x="{PAD["l"]}" y="{y1:.1f}" '
                     f'width="{W-PAD["l"]-PAD["r"]}" height="{y2-y1:.1f}"/>')
    parts.append(y_axis(vmin, vmax, sy, fmt))
    for i, v in enumerate(values):
        parts.append(f'<circle class="pt c-blue" cx="{sx(i):.1f}" cy="{sy(v):.1f}" r="2.6"/>')
    return f"""<figure class="card">
  <figcaption><h3>{title}</h3><p>{subtitle}</p></figcaption>
  <svg viewBox="0 0 {W} {H}" role="img" aria-label="{title}">{''.join(parts)}</svg>
</figure>"""


